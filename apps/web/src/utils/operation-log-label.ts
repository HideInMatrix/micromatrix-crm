function humanizeCode(value: string) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[-_]+/g, ' ')
    .trim()
}

export function operationModuleLabel(module: string) {
  return MODULE_LABELS[module] ?? humanizeCode(module)
}

export function operationActionLabel(action: string) {
  return ACTION_LABELS[action] ?? humanizeCode(action)
}
